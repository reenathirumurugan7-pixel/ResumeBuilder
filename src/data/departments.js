const aliasByName = new Map(
  Object.entries(DEPARTMENT_ALIASES).map(([name, aliases]) => [
    name.trim().toLowerCase(),
    aliases,
  ]),
)

function normalize(value) {
  return String(value || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ')
}

function buildSearchTokens(course, aliases) {
  return normalize([course, ...(aliases || [])].join(' '))
    .split(' ')
    .filter(Boolean)
}

const searchableCourses = DEPARTMENT_CATEGORIES.flatMap((category) =>
  category.courses.map((course) => ({
    name: course,
    category,
    searchTokens: buildSearchTokens(course, aliasByName.get(course.toLowerCase())),
  })),
)

function tokenMatches(searchToken, queryToken) {
  // Short abbreviations such as CS, IT, AI, CSE and MBA must match a whole
  // token. Prefix matching there would also pull in unrelated words such as
  // "airline" for AI or "computer" for CS.
  return queryToken.length <= 3
    ? searchToken === queryToken
    : searchToken.startsWith(queryToken)
}

function matchesQuery(course, query) {
  if (!query) return true

  const queryTokens = query.split(' ')
  const searchTokens = course.searchTokens

  if (queryTokens.length === 1) {
    return searchTokens.some((token) => tokenMatches(token, queryTokens[0]))
  }

  // Multi-word queries match a contiguous run of tokens, so "B.Com" cannot
  // match the "m com" inside "quantum computing".
  for (let i = 0; i <= searchTokens.length - queryTokens.length; i += 1) {
    let matched = true
    for (let j = 0; j < queryTokens.length; j += 1) {
      if (!tokenMatches(searchTokens[i + j], queryTokens[j])) {
        matched = false
        break
      }
    }
    if (matched) return true
  }

  return false
}

/**
 * Returns categories containing only the courses that match the query.
 * Search is case-insensitive, ignores punctuation and understands aliases.
 */
export function filterDepartments(query) {
  const normalizedQuery = normalize(query)
  if (!normalizedQuery) return DEPARTMENT_CATEGORIES

  return DEPARTMENT_CATEGORIES
    .map((category) => ({
      ...category,
      courses: searchableCourses
        .filter((course) => course.category.id === category.id)
        .filter((course) => matchesQuery(course, normalizedQuery))
        .map((course) => course.name),
    }))
    .filter((category) => category.courses.length > 0)
}

export function departmentCount() {
  return searchableCourses.length
}
